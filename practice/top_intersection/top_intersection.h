#pragma once

#include <vector>

// Legacy. Функция из старого модуля ранжирования (2022): пересечение
// двух топ-выдач. Работает, но на ревью — три замечания (см. комментарии
// ниже) и ТЗ в main.cpp.
//
// Спецификация (НЕ менять, только выполнять):
//   Входы: top_a, top_b — списки id. В КАЖДОМ списке id могут
//   ДУБЛИРОВАТЬСЯ.
//   Выход: vector<int> — id, встречающиеся в ОБОИХ списках, в порядке
//   ПЕРВОГО ВСТРЕЧЕНИЯ в top_a, каждый id — ровно один раз.
//
//   top_a = [5, 3, 5, 9], top_b = [3, 5, 9, 7]  ->  [5, 3, 9]
//   top_a = [], top_b = [1]                     ->  []
//   top_a = [1,2], top_b = [3,4]                ->  []
std::vector<int> IntersectTops(std::vector<int> top_a, std::vector<int> top_b) {
    std::vector<int> result;
    // Замечание ревьюера #1 (сложность):
    //   Двойной цикл: O(|top_a| * |top_b|). При 100k x 100k это 10^10
    //   операций — секунды/минуты. Нужно O(n + m).
    //
    // Замечание ревьюера #2 (порядок):
    //   Итерируем top_b НАРУЖУ — порядок в result = порядок top_b.
    //   Спецификация требует порядок ПЕРВОГО ВСТРЕЧЕНИЯ в top_a.
    //
    // Замечание ревьюера #3 (дубликаты):
    //   Если id есть в top_a дважды и в top_b — push_back сработает
    //   дважды (по вхождениям в top_a). Спецификация: каждый id — раз.
    for (std::size_t i = 0; i < top_b.size(); ++i) {
        for (std::size_t j = 0; j < top_a.size(); ++j) {
            if (top_b[i] == top_a[j]) {
                result.push_back(top_b[i]);
            }
        }
    }
    return result;
}
